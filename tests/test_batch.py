#!/usr/bin/env python3
"""Offline tests for lumix.batch with a simulated camera (no USB): python3 tests/test_batch.py"""
import os, struct, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..'))
from lumix import batch, luts
from lumix.ptp import CameraError, OK


class FakeCam:
    """Answers GetLutInfo, LutStartFileData and LutSendFileData like a DC-S9 in LUMIX Lab mode (272-byte records)."""
    def __init__(self, names):
        self.lib = {i: (n, s, t) for i, (n, s, t) in enumerate(names)}
        self.pending = None
        self.sent = []

    def tx(self, code, params, data=None, timeout=30000):
        if code == luts.GET_PARAM and params == [luts.GET_LUT_INFO]:
            recs = b''
            for i in range(41):
                n, s, t = self.lib.get(i, ('', 0, 3))
                recs += struct.pack('<H', i) + n.encode().ljust(256, b'\0') + struct.pack('<7H', s, t, 0, 0, 0, 0, 1 if n else 0)
            body = bytes([sum(1 for v in self.lib.values() if v[0])]) + recs
            return OK, [], struct.pack('<II', luts.GET_LUT_INFO, len(body)) + body
        if code == luts.LUT_START:
            self.pending = (params[0], data.split(b'\0')[0].decode())
            return OK, [], b''
        if code == luts.LUT_SEND:
            slot, name = self.pending
            head = data.decode().split('\n')[:3]
            tag = next((l.split()[1] for l in head if l.startswith('#LUMIXPHOTOSTYLE')), None)
            self.lib[slot] = (name, {'STD': 0, 'NAT': 2}.get(tag, 65535), 3)
            self.sent.append((slot, name, data))
            return OK, [], b''
        raise AssertionError(f'unexpected op 0x{code:04x}')


def cube(points=3):
    lines = ['TITLE "Generated by Resolve"', f'LUT_3D_SIZE {points}']
    for b in range(points):
        for g in range(points):
            for r in range(points):
                lines.append(' '.join(f'{v / (points - 1):.6f}' for v in (r, g, b)))
    return '\n'.join(lines) + '\n'


tmp = tempfile.mkdtemp()
for n in ('a', 'b', 'c'):
    open(os.path.join(tmp, f'{n}.cube'), 'w').write(cube())
open(os.path.join(tmp, 'big.cube'), 'w').write(cube(34))
man = os.path.join(tmp, 'm.csv')
open(man, 'w').write('# picks\na.cube,Look A\nb.cube,Look B\n\nc.cube,Look C,30\n')

items = batch.read_manifest(man)
assert [i['name'] for i in items] == ['Look A', 'Look B', 'Look C'] and items[2]['position'] == 30
assert os.path.isabs(items[0]['path'])

# V-Log base: no style tag; STD base: tag written; keep: a tag-less file stays tag-less
assert b'#LUMIXPHOTOSTYLE' not in batch.prepare(items[0]['path'], 'Look A', 'VLOG')
assert b'#LUMIXPHOTOSTYLE STD' in batch.prepare(items[0]['path'], 'Look A', 'STD')
assert b'#LUMIXPHOTOSTYLE' not in batch.prepare(items[0]['path'], 'Look A', None)
for bad in (lambda: batch.prepare(os.path.join(tmp, 'big.cube'), 'Big', 'VLOG'),
            lambda: batch.prepare(items[0]['path'], 'Ünïcode', 'VLOG')):
    try:
        bad(); raise SystemExit('expected CameraError')
    except CameraError:
        pass

# library: Vlog_709, ARRI sample, user LUTs at 2-3, a gap at 4, user LUT at 5
cam = FakeCam([('Vlog_709', 40, 1), ('ARRI 709', 65535, 2), ('Old 1', 0, 3), ('Old 2', 0, 3), ('', 0, 3), ('Old 3', 2, 3)])
steps = batch.plan(luts.library(cam), items)
assert [s['position'] for s in steps] == [4, 6, 30], steps  # gap first, then the next free; explicit 30 kept

# occupied position refused unless replace
try:
    batch.plan(luts.library(cam), [{'path': items[0]['path'], 'name': 'X', 'position': 3}]); raise SystemExit('expected refusal')
except CameraError as e:
    assert 'Old 2' in str(e)
assert batch.plan(luts.library(cam), [{'path': items[0]['path'], 'name': 'X', 'position': 3}], replace=True)[0]['replaces'] == 'Old 2'
# duplicate names refused
try:
    batch.plan(luts.library(cam), items + [{'path': items[0]['path'], 'name': 'Look A', 'position': None}]); raise SystemExit('expected refusal')
except CameraError:
    pass

# load uploads, verifies V-Log default base, and writes nothing if any file is bad
res = batch.load(cam, items, 'VLOG', log=lambda *_: None)
assert [r['position'] for r in res] == [4, 6, 30] and all(r['ok'] for r in res)
lib = {e['position']: e for e in luts.library(cam)}
assert lib[4]['name'] == 'Look A' and lib[4]['base_style'] is None and lib[4]['on_vlog_default']
cam2 = FakeCam([('Vlog_709', 40, 1), ('ARRI 709', 65535, 2)])
try:
    batch.load(cam2, items + [{'path': os.path.join(tmp, 'big.cube'), 'name': 'Big', 'position': None}], 'VLOG', log=lambda *_: None)
    raise SystemExit('expected refusal')
except CameraError:
    assert cam2.sent == [], 'nothing may be written when a file is invalid'

# full library
cam3 = FakeCam([('Vlog_709', 40, 1), ('ARRI 709', 65535, 2)] + [(f'L{i}', 0, 3) for i in range(2, 41)])
try:
    batch.plan(luts.library(cam3), items[:1]); raise SystemExit('expected full')
except CameraError as e:
    assert 'full' in str(e)
print('ok: batch tests passed')
